// Structure of the generated samples (samples/*, built by `npm run samples` with real Excel).
// Reads the packages directly (JSZip / SheetJS) — no Excel needed. Skipped when the samples were not generated.
import fs from 'node:fs';
import path from 'node:path';
import JSZip from 'jszip';
import * as XLSX from 'xlsx';
import Encoding from 'encoding-japanese';
import { describe, expect, it } from 'vitest';
import { buildSpec, buildTruth, FILES } from '../../tools/lib/sample-data.mjs';

const dir = path.resolve(__dirname, '../../samples');
const has = (f: string) => fs.existsSync(path.join(dir, f));
const allXlsx = [FILES.base, FILES.interview, FILES.aptitude, FILES.attendance].every(has);

async function pkg(file: string) {
  const zip = await JSZip.loadAsync(fs.readFileSync(path.join(dir, file)));
  const text = async (p: string) => {
    const f = zip.file(p);
    if (!f) throw new Error(`missing part ${p}`);
    return f.async('string');
  };
  const wb = await text('xl/workbook.xml');
  const rels = await text('xl/_rels/workbook.xml.rels');
  const sheetPath = async (name: string) => {
    const m = new RegExp(`<sheet [^>]*name="${name}"[^>]*r:id="(rId\\d+)"`).exec(wb);
    if (!m) throw new Error(`no sheet ${name}`);
    const t = new RegExp(`Id="${m[1]}"[^>]*Target="([^"]+)"`).exec(rels) ?? new RegExp(`Target="([^"]+)"[^>]*Id="${m[1]}"`).exec(rels);
    return 'xl/' + t![1].replace(/^\/?xl\//, '');
  };
  return { zip, wb, text, sheet: async (name: string) => text(await sheetPath(name)), files: Object.keys(zip.files) };
}

describe.skipIf(!allXlsx)('samples (generated by npm run samples)', () => {
  it('truth.json is up to date with the generator', () => {
    const disk = JSON.parse(fs.readFileSync(path.join(dir, 'truth.json'), 'utf8'));
    expect(disk).toEqual(JSON.parse(JSON.stringify(buildTruth(buildSpec()))));
  });

  it('01_学生名簿: sheets, names, title merge, freeze, filter, hidden helper, CF, DV', async () => {
    const p = await pkg(FILES.base);
    const sheets = [...p.wb.matchAll(/<sheet [^>]*name="([^"]+)"/g)].map((m) => m[1]);
    expect(sheets).toEqual(['名簿', '集計', 'ピボット', 'マスタ']);
    expect(p.wb).toContain('<definedName name="大学一覧">マスタ!$A$2:$A$20</definedName>');
    expect(p.wb).toContain('<definedName name="志望度列">名簿!$K:$K</definedName>');
    expect(p.wb).toContain('<definedName name="基準日">マスタ!$H$2</definedName>');
    const s = await p.sheet('名簿');
    expect(s).toContain('<mergeCell ref="A1:K1"/>');
    expect(s).toMatch(/<pane xSplit="2" ySplit="3" topLeftCell="C4"[^>]*state="frozen"/);
    expect(s).toMatch(/<autoFilter ref="A3:L63"/);
    expect(s).toMatch(/<col min="12" max="12"[^>]*hidden="1"/);
    expect((s.match(/<conditionalFormatting /g) ?? []).length).toBe(2);
    expect(s).toContain('<formula>$L4&gt;1</formula>');
    // 志望度 list is a normal DV, the マスタ list is an x14 (extLst) DV because it points to another sheet
    expect(s).toMatch(/<dataValidation type="list"[^>]*sqref="K4:K63"/);
    expect(s).toMatch(/<x14:dataValidation type="list"[\s\S]*マスタ!\$A\$2:\$A\$20[\s\S]*<xm:sqref>D4:D63<\/xm:sqref>/);
    expect(s).toContain('<f>DATEDIF(I4,基準日,"Y")</f>');
    // chart + pivot parts exist
    expect(p.files.some((f) => /^xl\/charts\/chart\d+\.xml$/.test(f))).toBe(true);
    expect(p.files.some((f) => /^xl\/pivotTables\/pivotTable\d+\.xml$/.test(f))).toBe(true);
    const cacheDef = await p.text(p.files.find((f) => /^xl\/pivotCache\/pivotCacheDefinition\d+\.xml$/.test(f))!);
    expect(cacheDef).toMatch(/<worksheetSource ref="A3:L63" sheet="名簿"\/>/);
    const sum = await p.sheet('集計');
    expect(sum).toContain('COUNTIF(名簿!$D:$D,$A5)');
    expect(sum).toContain('SUMPRODUCT((名簿!$D$4:$D$63=$A5)*名簿!$K$4:$K$63)');
  });

  it('01_学生名簿: values as a reader sees them (text IDs, dates, cached formula results)', () => {
    const wb = XLSX.read(fs.readFileSync(path.join(dir, FILES.base)), { type: 'buffer', cellFormula: true, cellNF: true });
    const ws = wb.Sheets['名簿'];
    expect(ws['A3'].v).toBe('学生ID');
    expect(ws['A4'].t).toBe('s');
    expect(ws['A4'].v).toBe('000100');
    expect(ws['I4'].t).toBe('n');
    // Japanese Excel stores 'yyyy/m/d' as the BUILT-IN format id 14 (SheetJS names id 14 'm/d/yy'; our reader
    // must resolve it to the ja-JP code 'yyyy/m/d')
    expect(['yyyy/m/d', 'm/d/yy']).toContain(ws['I4'].z);
    expect(ws['J4'].f).toBe('DATEDIF(I4,基準日,"Y")');
    expect(typeof ws['J4'].v).toBe('number');
    expect(ws['B65'].f).toBe('COUNTA(B4:B63)');
    expect(ws['B65'].v).toBe(60);
    const sum = wb.Sheets['集計'];
    expect(sum['B15'].v).toBe(60);
    expect(sum['B30'].v).toBe(2); // 同姓同名の件数
  });

  it('02_面接評価: mixed ID storage, colour scale, table sheet with structured refs', async () => {
    const wb = XLSX.read(fs.readFileSync(path.join(dir, FILES.interview)), { type: 'buffer', cellFormula: true });
    const ws = wb.Sheets['面接評価'];
    const ids = XLSX.utils.sheet_to_json<unknown[]>(ws, { header: 1, raw: true }).slice(1).map((r) => r[0]);
    expect(ids.some((v) => typeof v === 'number')).toBe(true);
    expect(ids.some((v) => typeof v === 'string' && /^0\d{5}$/.test(v))).toBe(true);
    expect(ids.some((v) => typeof v === 'string' && /^[０-９]{6}$/.test(v))).toBe(true);
    expect(ws['G2'].f).toBe('AVERAGE(D2:F2)');
    const p = await pkg(FILES.interview);
    expect(await p.sheet('面接評価')).toContain('<colorScale>');
    const table = await p.text(p.files.find((f) => /^xl\/tables\/table\d+\.xml$/.test(f))!);
    expect(table).toMatch(/name="面接評価表"/);
    expect(await p.sheet('評価テーブル')).toMatch(/面接評価表\[\[#This Row\],\[評価1\]:\[評価3\]\]/);
  });

  it('03_連絡先.csv is Shift_JIS with CRLF and no ID column', () => {
    const buf = fs.readFileSync(path.join(dir, FILES.contacts));
    expect(Encoding.detect(buf)).toBe('SJIS');
    const text = Encoding.codeToString(Encoding.convert(Array.from(buf), { to: 'UNICODE', from: 'SJIS' }));
    const lines = text.split('\r\n');
    expect(lines[0]).toBe('氏名,メール,電話');
    expect(lines.length).toBe(48 + 1); // header + 47 rows + trailing empty
    expect(text).not.toContain('�');
  });

  it('04_適性検査.xls is a real BIFF8 file with kana and unrelated 学籍番号', () => {
    const buf = fs.readFileSync(path.join(dir, FILES.aptitude));
    expect([...buf.subarray(0, 8)]).toEqual([0xd0, 0xcf, 0x11, 0xe0, 0xa1, 0xb1, 0x1a, 0xe1]); // OLE2 compound file
    const wb = XLSX.read(buf, { type: 'buffer', cellFormula: true });
    expect(wb.SheetNames).toEqual(['適性検査結果']);
    const rows = XLSX.utils.sheet_to_json<unknown[]>(wb.Sheets['適性検査結果'], { header: 1, raw: true });
    expect(rows[0]).toEqual(['学籍番号', '氏名カナ', '受検日', '言語', '非言語', '合計', '性格タイプ', '総合判定']);
    expect(rows).toHaveLength(43);
    expect(rows.slice(1).some((r) => /[ｦ-ﾟ]/.test(String(r[1])))).toBe(true);
    expect(wb.Sheets['適性検査結果']['F2'].f).toBe('D2+E2');
  });

  it('05_研修出欠: title row, header row 2, composite-key data', () => {
    const wb = XLSX.read(fs.readFileSync(path.join(dir, FILES.attendance)), { type: 'buffer' });
    const ws = wb.Sheets['出欠'];
    expect(ws['A2'].v).toBe('氏名');
    expect(ws['B2'].v).toBe('大学');
    expect(ws['!merges']?.[0]).toEqual({ s: { r: 0, c: 0 }, e: { r: 0, c: 6 } });
    const rows = XLSX.utils.sheet_to_json<unknown[]>(ws, { header: 1, raw: true }).slice(2);
    expect(rows.filter((r) => r[0] === '佐藤 翔太')).toHaveLength(2);
  });
});
