/**
 * The import-values oracle (oracle.ts) under vitest.
 *  - always: the Node half runs on the repository fixtures (tests/fixtures/formulaimport) without Excel — every premerged package and its
 *    column-moved twin is built, nothing may throw;
 *  - EXCEL_TESTS=1: the whole oracle with real Excel (run.ps1 -> ONE hidden instance of our own): every package opens without repair, every
 *    live formula has the value it has in the original file recalculated by Excel, no stale result is stored, a column move keeps all values.
 *    The corpus is the one in tests/fixtures/formulaimport (5 configurations x 18 files); the full corpus (45 files) is regenerated by
 *    run.ps1 -Regenerate.
 */
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { main } from './oracle';

const FIX = path.resolve(__dirname, '../../fixtures/formulaimport');
const EXCEL = process.env.EXCEL_TESTS === '1';

describe('import-values oracle: Node half (no Excel)', () => {
  it('builds every premerged package and its column-moved twin for the fixtures', async () => {
    const out = fs.mkdtempSync(path.join(os.tmpdir(), 'iv-oracle-'));
    try {
      await main(['--corpus', FIX, '--out', out, '--configs', 'quick', '--no-excel']);
      const pkgs = fs.readdirSync(path.join(out, 'pkg'));
      expect(pkgs.filter((f) => f.endsWith('.moved.xlsx')).length).toBe(pkgs.filter((f) => !f.endsWith('.moved.xlsx')).length);
      expect(pkgs.length).toBeGreaterThanOrEqual(30);
      const jobs = JSON.parse(fs.readFileSync(path.join(out, 'jobs.json'), 'utf8')) as Array<{ kind: string }>;
      expect(jobs.some((j) => j.kind === 'reduced')).toBe(true);
    } finally {
      fs.rmSync(out, { recursive: true, force: true });
    }
  }, 120_000);
});

describe.skipIf(!EXCEL)('import-values oracle: real Excel (EXCEL_TESTS=1)', () => {
  it('all packages open without repair, live formulas keep their values, no stale results, column moves keep every value', async () => {
    const out = fs.mkdtempSync(path.join(os.tmpdir(), 'iv-oracle-xl-'));
    try {
      const ps1 = path.resolve(__dirname, 'run.ps1');
      // asynchronous: a blocking call would starve vitest's worker heartbeat for the minutes Excel needs
      const code = await new Promise<number | null>((resolve, reject) => {
        const child = spawn('powershell.exe', ['-NoLogo', '-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', ps1, '-Corpus', FIX, '-Out', out], { stdio: ['ignore', 'inherit', 'inherit'] });
        const timer = setTimeout(() => child.kill(), 25 * 60_000);
        child.on('error', reject);
        child.on('close', (c) => { clearTimeout(timer); resolve(c); });
      });
      expect(code).toBe(0);
      const rs = JSON.parse(fs.readFileSync(path.join(out, 'results.json'), 'utf8')) as Array<Record<string, number | string>>;
      expect(rs.length).toBeGreaterThan(80);
      expect(rs.filter((r) => r.open !== 'normal' || r.moveOpen !== 'normal')).toEqual([]);
      expect(rs.reduce((a, r) => a + (r.mismatches as number), 0)).toBe(0);
      expect(rs.reduce((a, r) => a + (r.staleCache as number), 0)).toBe(0);
      expect(rs.reduce((a, r) => a + (r.moveMismatch as number), 0)).toBe(0);
      expect(rs.reduce((a, r) => a + (r.compared as number), 0)).toBeGreaterThan(5000);
    } finally {
      fs.rmSync(out, { recursive: true, force: true });
    }
  }, 30 * 60_000);
});
