/**
 * Runs a MessyCase (tests/fixtures/keys/messy/*) through the facade — the xlsx files are read with the APP's reader —
 * and scores the result against the ground truth recorded by the fixture builders (row → person).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { JoinPlan, JoinResult, KeyAnalysis, KeySource } from '../../src/core/contracts';
import { analyzeSources, defaultPlan, detectRegion, joinSources, pickDataSheet } from '../../src/core/keys';
import { readBook } from '../../src/core/xlsx';
import type { MessyCase, MessyFile } from '../fixtures/keys/messy/lib';
import { toXlsxBytes } from '../fixtures/keys/messy/lib';

export const MESSY_DIR = fileURLToPath(new URL('../fixtures/keys/messy', import.meta.url));

export interface OtherEval {
  id: string;
  /** automatic matches whose two rows are the same person */
  correct: number;
  /** automatic matches between different persons (or onto a row that is not a person) — must always be empty */
  wrong: string[];
  /** base rows that have a counterpart person in the other file but were not joined */
  missed: Array<{ baseRow: number; otherRow: number; person: string; surfaced: 'suggestion' | 'ambiguous' | null }>;
  /** selected plan (candidate labels in tier order) */
  plan: string[];
  /** appended rows ('full') that are not a person of the other file (blank / header / subtotal rows) */
  junkAppended: string[];
  /** appended rows whose person also exists in the base (duplicated people) */
  duplicatedPeople: string[];
}

export interface CaseRun {
  c: MessyCase;
  sources: KeySource[];
  an: KeyAnalysis;
  plan: JoinPlan;
  res: JoinResult;
  evals: Record<string, OtherEval>;
  codes: Set<string>;
  ms: { analyze: number; join: number };
}

export async function sourceOfFile(f: MessyFile, bytes?: Uint8Array): Promise<KeySource> {
  const book = await readBook(bytes ?? toXlsxBytes(f), f.fileName, { id: f.id });
  const sheet = f.dataSheet ?? pickDataSheet(book);
  return { id: f.id, book, region: detectRegion(book, sheet), label: f.fileName.replace(/\.[^.]+$/, '') };
}

/** the committed xlsx of a fixture file (falls back to the generated bytes when the file is not there) */
export function committedPath(caseName: string, f: MessyFile): string {
  return path.join(MESSY_DIR, 'out', caseName, f.fileName);
}

export async function runCase(c: MessyCase, opts: { fromDisk?: boolean; plan?: Partial<JoinPlan> } = {}): Promise<CaseRun> {
  const sources: KeySource[] = [];
  for (const f of c.files) {
    const p = committedPath(c.name, f);
    const bytes = opts.fromDisk && fs.existsSync(p) ? new Uint8Array(fs.readFileSync(p)) : undefined;
    sources.push(await sourceOfFile(f, bytes));
  }
  const t0 = performance.now();
  const an = analyzeSources(sources[0], sources.slice(1));
  const t1 = performance.now();
  const plan: JoinPlan = { ...defaultPlan(an), ...(c.plan ?? {}), ...(opts.plan ?? {}) } as JoinPlan;
  const res = joinSources(an, plan);
  const t2 = performance.now();
  const base = c.files[0];
  const evals: Record<string, OtherEval> = {};
  for (const f of c.files.slice(1)) evals[f.id] = evaluateOther(base, f, an, plan, res);
  const codes = new Set(res.items.map((i) => `${i.sourceId ?? ''}:${i.code}`));
  return { c, sources, an, plan, res, evals, codes, ms: { analyze: t1 - t0, join: t2 - t1 } };
}

export function evaluateOther(base: MessyFile, other: MessyFile, an: KeyAnalysis, plan: JoinPlan, res: JoinResult): OtherEval {
  const id = other.id;
  const tb = base.truth;
  const to = other.truth;
  const personsOther = new Map<string, number[]>();
  for (const [r, p] of Object.entries(to)) personsOther.set(p, [...(personsOther.get(p) ?? []), Number(r)]);
  let correct = 0;
  const wrong: string[] = [];
  const matchedBase = new Set<number>();
  const junkAppended: string[] = [];
  const duplicatedPeople: string[] = [];
  const basePersons = new Set(Object.values(tb));
  for (const row of res.rows) {
    const m = row.matches[id];
    if (!m) continue;
    if (row.baseRow === null) {
      const p = to[m.row];
      if (p === undefined) junkAppended.push(`${other.fileName}:${m.row}`);
      else if (basePersons.has(p)) duplicatedPeople.push(`${p}@${m.row}`);
      continue;
    }
    const x = tb[row.baseRow];
    const y = to[m.row];
    if (x !== undefined && x === y) {
      correct++;
      matchedBase.add(row.baseRow);
    } else wrong.push(`${row.baseRow}:${x ?? '-'} ⟷ ${m.row}:${y ?? '-'} via ${m.via}`);
  }
  // appended rows of OTHER sources can also carry a match of this source (full join, sequential): skip those
  const rep = res.reports[id];
  const sugg = new Map<number, Set<number>>();
  for (const s of rep?.suggestions ?? []) (sugg.get(s.base.excelRow) ?? sugg.set(s.base.excelRow, new Set()).get(s.base.excelRow)!).add(s.other.excelRow);
  const amb = new Map<number, Set<number>>();
  for (const a of rep?.ambiguous ?? []) for (const c of a.candidates) (amb.get(a.base.excelRow) ?? amb.set(a.base.excelRow, new Set()).get(a.base.excelRow)!).add(c.excelRow);
  const missed: OtherEval['missed'] = [];
  for (const [rowStr, p] of Object.entries(tb)) {
    const baseRow = Number(rowStr);
    if (matchedBase.has(baseRow)) continue;
    const others = personsOther.get(p);
    if (!others) continue;
    const surf = others.some((o) => amb.get(baseRow)?.has(o)) ? 'ambiguous' : others.some((o) => sugg.get(baseRow)?.has(o)) ? 'suggestion' : null;
    missed.push({ baseRow, otherRow: others[0], person: p, surfaced: surf });
  }
  const cands = an.pairs[id]?.candidates ?? [];
  const planLabels = (plan.tiers[id] ?? []).map((cid) => cands.find((c) => c.id === cid)?.label ?? cid);
  return { id, correct, wrong, missed, plan: planLabels, junkAppended, duplicatedPeople };
}
